/**
 * Paper-ready summary of a build (counts, changes, lifespan sources, correlation comparison),
 * printed as markdown from the committed output:
 *   bun run pipeline/report.ts [build1-correlations.json] > /tmp/report.md
 * The optional argument is the build 1 site's src/data/generated/correlations.json (e.g. from
 * `git show <build-1 commit>:src/data/generated/correlations.json`), added to the comparison.
 */
import { readdirSync, statSync } from "node:fs";
import { join, relative } from "node:path";
import type { Correlation, Species } from "../src/data/schema";
import { ROOT } from "./lib/cache";
import { readParquet } from "./lib/parquet";
import { GENERATED_DIR, PUBLIC_DATA_DIR } from "./steps/output";

const data = await import("../src/data/index");
const out: string[] = [];
const p = (s = "") => out.push(s);
const table = (head: string[], rows: (string | number)[][]) => {
  p(`| ${head.join(" | ")} |`);
  p(`| ${head.map((_, i) => (i === 0 ? "---" : "---:")).join(" | ")} |`);
  for (const r of rows) p(`| ${r.join(" | ")} |`);
  p();
};
const countBy = <T>(xs: T[], key: (x: T) => string) => {
  const m = new Map<string, number>();
  for (const x of xs) m.set(key(x), (m.get(key(x)) ?? 0) + 1);
  return m;
};
const crosstab = <T>(xs: T[], row: (x: T) => string, col: (x: T) => string, colOrder?: string[]) => {
  const cols = colOrder ?? [...new Set(xs.map(col))].sort();
  const rows = [...new Set(xs.map(row))].sort();
  const body = rows.map((r) => {
    const cells = cols.map((c) => xs.filter((x) => row(x) === r && col(x) === c).length);
    return [r, ...cells, cells.reduce((a, b) => a + b, 0)];
  });
  const tot = cols.map((c) => xs.filter((x) => col(x) === c).length);
  body.push(["total", ...tot, tot.reduce((a, b) => a + b, 0)]);
  return { head: ["", ...cols, "total"], body };
};

const info = data.getBuildInfo();
const species = data.getAllSpecies();
const status = (s: Species) => s.provenance?.recordStatus ?? "?";
p(`# Build ${info.build}: summary tables`);
p();
p("Generated by `bun run pipeline/report.ts` from the committed output.");
p();

p("## Species by record status");
p();
table(["record_status", "species"], ["original", "updated", "renamed", "retired", "new"].map((k) => [k, species.filter((s) => status(s) === k).length]));
const sources = ["AnAge", "FishBase", "SeaLifeBase", "USGS_BBL", "MitoAge_build1"];
p("## New species: class x lifespan source");
p();
{
  const c = crosstab(species.filter((s) => status(s) === "new"), (s) => s.taxonomy.class || "(no class)", (s) => s.lifespan!.source, sources.slice(0, 4));
  table(c.head, c.body);
}
p("## All non-retired species: class x lifespan source");
p();
{
  const c = crosstab(species.filter((s) => status(s) !== "retired"), (s) => s.taxonomy.class || "(no class)", (s) => s.lifespan!.source, sources.slice(0, 4));
  table(c.head, c.body);
}
p("## Lifespan source x quality and x record type (non-retired species)");
p();
{
  const live = species.filter((s) => status(s) !== "retired");
  const q = crosstab(live, (s) => s.lifespan!.source, (s) => s.lifespan!.quality ?? "(none)");
  table(q.head, q.body);
  const r = crosstab(live, (s) => s.lifespan!.source, (s) => s.lifespan!.recordType);
  table(r.head, r.body);
}
p("## Retired species");
p();
table(["species", "refseq (build 1)", "reason"], species.filter((s) => status(s) === "retired").map((s) => [`${s.scientificName} (${s.id})`, s.refseq, (s.retiredReason ?? "").replace(/\|/g, "/")]));

const cl = await readParquet(join(PUBLIC_DATA_DIR, "changelog.parquet"));
p("## Changelog rows: table x change_type");
p();
{
  const c = crosstab(cl, (r) => String(r["table"]), (r) => String(r["change_type"]));
  table(c.head, c.body);
}
p("## Changelog rows by diff_class");
p();
table(["diff_class", "change_type", "scope", "rows", "species"], [...countBy(cl, (r) => `${r["diff_class"]}|${r["change_type"]}|${r["scope"]}`)].sort((a, b) => b[1] - a[1]).map(([k, v]) => {
  const [dc, ct, sc] = k.split("|");
  const sp = new Set(cl.filter((r) => r["diff_class"] === dc && r["change_type"] === ct && r["scope"] === sc).map((r) => String(r["row_key"]).split(":")[0])).size;
  return [dc!, ct!, sc!, v, sp];
}));
p("## Changelog rows by table and field (build 1 species, top 40)");
p();
const b1 = new Set(species.filter((s) => s.provenance?.addedInBuild === 1).map((s) => String(s.id)));
const onB1 = cl.filter((r) => b1.has(String(r["row_key"]).split(":")[0]!));
table(["table", "field", "rows"], [...countBy(onB1, (r) => `${r["table"]}|${r["field"]}`)].sort((a, b) => b[1] - a[1]).slice(0, 40).map(([k, v]) => [...k.split("|"), v]));
p("## Build 1 species: what changed (change_kinds; a species can have several)");
p();
table(["kind", "species"], [...countBy(species.filter((s) => s.provenance?.addedInBuild === 1).flatMap((s) => s.changeKinds ?? []), (k) => k)].sort((a, b) => b[1] - a[1]));
p("## Rows per table and record_status");
p();
{
  const rows: (string | number)[][] = [];
  for (const t of ["region_stats", "codon_usage", "genome_features", "lifespan_observations"]) {
    const r = await readParquet(join(PUBLIC_DATA_DIR, `${t}.parquet`), ["record_status"]);
    const c = countBy(r, (x) => String(x["record_status"]));
    rows.push([t, ...["original", "updated", "new", "retired"].map((k) => c.get(k) ?? 0), r.length]);
  }
  table(["table", "original", "updated", "new", "retired", "total"], rows);
}
p("## Review flags (species)");
p();
table(["flag", "species"], [...countBy(species.flatMap((s) => (s.reviewFlags ?? []).map((f) => f.split(":")[0]!)), (k) => k)].sort((a, b) => b[1] - a[1]));

// ------------------------------------------------------------------ correlations
p("## Correlation datasets");
p();
table(["dataset", "species", "lifespan sources", "filters"], (info.correlationDatasets ?? []).map((d) => [d.dataset, d.species, d.lifespanSources.join(", "), d.filters]));
const b1Path = process.argv[2];
let b1corr: Map<string, { n: number; r: number; p: number; pic: number | null }> | null = null;
if (b1Path) {
  const f = (await Bun.file(b1Path).json()) as { features: string[]; traits: string[]; scopes: string[]; columns: Record<string, (number | null)[]> };
  b1corr = new Map();
  const c = f.columns;
  c["feature"]!.forEach((fi, i) => {
    b1corr!.set(`${f.features[fi!]}|${f.traits[c["trait"]![i]!]}|${f.scopes[c["scope"]![i]!]}`, { n: c["n"]![i]!, r: c["pearsonR"]![i]!, p: c["pValue"]![i]!, pic: c["picR"]![i] ?? null });
  });
}
const KEYS = ["gc:total_mtDNA", "size:total_mtDNA", "noncoding:total_mtDNA", "gcSkew:total_mtDNA", "atSkew:total_mtDNA", "gc:total_pc", "gc:D_Loop", "size:D_Loop", "gc:rRNA-12S", "gc:ND6", "gcSkew:ND6"];
const fmt = (v: number | null | undefined, d = 3) => (v === null || v === undefined || !Number.isFinite(v) ? "-" : v.toFixed(d));
const fp = (v: number | null | undefined) => (v === null || v === undefined || !Number.isFinite(v) ? "-" : v < 1e-3 ? v.toExponential(1) : v.toFixed(3));
for (const scope of ["all", "class:Mammalia", "class:Aves", "class:Actinopterygii", "class:Reptilia"]) {
  p(`### Maximum lifespan (log10) vs mtDNA features, scope ${scope}`);
  p();
  const rows: (string | number)[][] = [];
  for (const k of KEYS) {
    const get = (d: "default" | "anage_only") => data.getCorrelations({ featureKey: k, trait: "maxLongevityYears", scope, dataset: d })[0];
    const d = get("default");
    const a = get("anage_only");
    const o = b1corr?.get(`${k}|maxLongevityYears|${scope}`);
    rows.push([
      k,
      ...(b1corr ? [o ? `${o.n}` : "-", fmt(o?.r), fp(o?.p)] : []),
      a ? a.n : "-", fmt(a?.pearsonR), fp(a?.pValue), fmt(a?.picR),
      d ? d.n : "-", fmt(d?.pearsonR), fp(d?.pValue), fmt(d?.picR),
    ]);
  }
  table(["feature", ...(b1corr ? ["build 1 n", "build 1 r", "build 1 p"] : []), "AnAge-only n", "r", "p", "PIC r", "extended n", "r", "p", "PIC r"], rows);
}
p("### Agreement between the datasets (maximum lifespan, all features)");
p();
{
  const rows: (string | number)[][] = [];
  for (const scope of ["all", "class:Mammalia", "class:Aves", "class:Actinopterygii"]) {
    const d = new Map(data.getCorrelations({ trait: "maxLongevityYears", scope, dataset: "default" }).map((c) => [c.featureKey, c]));
    const a = new Map(data.getCorrelations({ trait: "maxLongevityYears", scope, dataset: "anage_only" }).map((c) => [c.featureKey, c]));
    const both = [...d.keys()].filter((k) => a.has(k));
    const xs = both.map((k) => a.get(k)!.pearsonR);
    const ys = both.map((k) => d.get(k)!.pearsonR);
    const mx = xs.reduce((s, v) => s + v, 0) / xs.length;
    const my = ys.reduce((s, v) => s + v, 0) / ys.length;
    let sxy = 0, sxx = 0, syy = 0;
    xs.forEach((x, i) => { sxy += (x - mx) * (ys[i]! - my); sxx += (x - mx) ** 2; syy += (ys[i]! - my) ** 2; });
    const sig = (m: Map<string, Correlation>) => [...m.values()].filter((c) => c.qValue < 0.05).length;
    const signAgree = both.filter((k) => Math.sign(a.get(k)!.pearsonR) === Math.sign(d.get(k)!.pearsonR)).length;
    rows.push([scope, both.length, (sxy / Math.sqrt(sxx * syy)).toFixed(3), `${signAgree}/${both.length}`, sig(a), sig(d)]);
  }
  table(["scope", "features in both", "r between the two r vectors", "same sign", "q < 0.05 (AnAge-only)", "q < 0.05 (extended)"], rows);
}

// ------------------------------------------------------------------ sources and files
p("## Pinned upstream versions");
p();
table(["source", "version", "licence"], info.sources.map((s) => [s.name, s.version.replace(/\|/g, "/"), s.license.replace(/\|/g, "/")]));
p("## Committed output files");
p();
const walk = (d: string): string[] => readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(join(d, e.name)) : [join(d, e.name)]));
const files = [...walk(GENERATED_DIR), ...walk(PUBLIC_DATA_DIR)].sort();
table(["file", "bytes"], files.map((f) => [relative(ROOT, f), statSync(f).size]));
p(`Largest committed file: ${Math.max(...files.map((f) => statSync(f).size))} bytes; total ${files.reduce((s, f) => s + statSync(f).size, 0)} bytes in ${files.length} files.`);
console.log(out.join("\n"));
