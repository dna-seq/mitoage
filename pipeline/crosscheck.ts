/**
 * Cross-check of the build 2 output against the reference tables of the build 2 audit (Python, not
 * in the repository) in data/cache/build2/{candidates,verification}. The audit tables are read here
 * only to compare: the pipeline never reads them. Prints a markdown report:
 *   bun run pipeline/crosscheck.ts > docs/BUILD2_CROSSCHECK.md
 */
import { existsSync } from "node:fs";
import { join } from "node:path";
import { CACHE_DIR } from "./lib/cache";
import { type Row, readParquet } from "./lib/parquet";
import { PUBLIC_DATA_DIR } from "./steps/output";

const AUDIT = join(CACHE_DIR, "build2");
const need = ["candidates/build2_candidate_species.parquet", "candidates/build2_lifespan_observations.parquet", "verification/verification_diff_build1.parquet", "verification/verification_species_summary.parquet"];
for (const f of need) if (!existsSync(join(AUDIT, f))) throw new Error(`audit table missing: data/cache/build2/${f}`);

const out: string[] = [];
const p = (s = "") => out.push(s);
const table = (head: string[], rows: (string | number)[][]) => {
  p(`| ${head.join(" | ")} |`);
  p(`| ${head.map(() => "---").join(" | ")} |`);
  for (const r of rows) p(`| ${r.join(" | ")} |`);
  p();
};
const pct = (a: number, b: number) => (b ? `${((100 * a) / b).toFixed(1)}%` : "n/a");
const s = (v: unknown) => (v === null || v === undefined ? "" : String(v));
const sameValue = (a: unknown, b: unknown) => {
  if (s(a) === s(b)) return true;
  const x = Number(a);
  const y = Number(b);
  return s(a) !== "" && s(b) !== "" && Number.isFinite(x) && Number.isFinite(y) && Math.abs(x - y) < 1e-6;
};
const countBy = <T>(xs: T[], key: (x: T) => string) => {
  const m = new Map<string, number>();
  for (const x of xs) m.set(key(x), (m.get(key(x)) ?? 0) + 1);
  return [...m].sort((a, b) => b[1] - a[1] || (a[0] < b[0] ? -1 : 1));
};

const species = await readParquet(join(PUBLIC_DATA_DIR, "species.parquet"));
const changelog = await readParquet(join(PUBLIC_DATA_DIR, "changelog.parquet"));
const obs = await readParquet(join(PUBLIC_DATA_DIR, "lifespan_observations.parquet"));
const cand = await readParquet(join(AUDIT, need[0]!));
const aobs = await readParquet(join(AUDIT, need[1]!));
const vdiff = await readParquet(join(AUDIT, need[2]!));
const vsum = await readParquet(join(AUDIT, need[3]!));

p("# Build 2 cross-check against the audit reference tables");
p();
p("Generated by `bun run pipeline/crosscheck.ts` from public/data/*.parquet (the TypeScript pipeline's output) and the");
p("audit tables in data/cache/build2/ (produced by the Python audit scripts, not in the repository). The audit tables are");
p("used only here, as a check; the pipeline computes every value from the pinned upstream sources.");
p();

// ------------------------------------------------------------------ candidates
const mine = new Map(species.filter((r) => r["record_status"] === "new").map((r) => [Number(r["ncbi_species_taxid"]), r]));
const theirs = new Map(cand.map((r) => [Number(r["ncbi_taxid"]), r]));
const both = [...mine.keys()].filter((t) => theirs.has(t));
p("## 1. New species (candidate set)");
p();
table(["", "count"], [
  ["new species in build 2 (TS)", mine.size],
  ["candidates in the audit", theirs.size],
  ["in both (by NCBI species taxid)", both.length],
  ["only in TS", [...mine.keys()].filter((t) => !theirs.has(t)).length],
  ["only in the audit", [...theirs.keys()].filter((t) => !mine.has(t)).length],
]);
const fields: [string, string, string][] = [
  ["max_longevity_years", "max_longevity_years", "lifespan value"],
  ["lifespan_source", "lifespan_source", "lifespan source"],
  ["lifespan_source_record_id", "lifespan_source_record_id", "source record id"],
  ["lifespan_quality", "lifespan_quality", "quality"],
  ["lifespan_record_type", "lifespan_record_type", "record type"],
  ["refseq", "refseq_accession", "RefSeq accession.version"],
  ["scientific_name", "scientific_name", "scientific name"],
  ["class", "class", "class (build 1 scheme)"],
  ["order", "order", "order"],
  ["family", "family", "family"],
  ["common_name", "common_name", "common name"],
  ["lifespan_sample_size", "lifespan_sample_size", "AnAge sample size"],
];
const candRows: (string | number)[][] = [];
const candDis: string[] = [];
for (const [mf, af, label] of fields) {
  let agree = 0;
  for (const t of both) {
    if (sameValue(mine.get(t)![mf], theirs.get(t)![af])) agree++;
    else if (candDis.length < 40) candDis.push(`${label}: ${mine.get(t)!["scientific_name"]} (taxid ${t}): TS \`${s(mine.get(t)![mf])}\`, audit \`${s(theirs.get(t)![af])}\``);
  }
  candRows.push([label, `${agree}/${both.length}`, pct(agree, both.length)]);
}
table(["field", "agree", "%"], candRows);
if (candDis.length) {
  p("Disagreements (first 40):");
  p();
  for (const d of candDis) p(`- ${d}`);
  p();
}

// ------------------------------------------------------------------ observations
p("## 2. Lifespan observations");
p();
const okey = (taxid: unknown, source: unknown, id: unknown) => `${taxid}|${source}|${id}`;
const mo = new Map(obs.map((r) => [okey(r["ncbi_species_taxid"], r["source"], r["source_record_id"]), r]));
const ao = new Map(aobs.map((r) => [okey(r["ncbi_taxid"], r["source"], r["source_record_id"]), r]));
const ob = [...mo.keys()].filter((k) => ao.has(k));
const valueAgree = ob.filter((k) => sameValue(mo.get(k)!["value_years"], ao.get(k)!["value_years"])).length;
const chosenAgree = ob.filter((k) => Boolean(mo.get(k)!["is_chosen"]) === Boolean(ao.get(k)!["is_chosen"])).length;
table(["", "count"], [
  ["rows (TS)", mo.size],
  ["rows (audit)", ao.size],
  ["same (species taxid, source, record id)", ob.length],
  ["value agrees", `${valueAgree}/${ob.length}`],
  ["is_chosen agrees", `${chosenAgree}/${ob.length}`],
  ["only TS", mo.size - ob.length],
  ["only audit", ao.size - ob.length],
]);
const onlyMine = [...mo.keys()].filter((k) => !ao.has(k));
const onlyTheirs = [...ao.keys()].filter((k) => !mo.has(k));
if (onlyMine.length || onlyTheirs.length) {
  p("Rows on one side only, by source:");
  p();
  table(["side", "source", "rows"], [
    ...countBy(onlyMine, (k) => k.split("|")[1]!).map(([k, v]) => ["TS only", k, v]),
    ...countBy(onlyTheirs, (k) => k.split("|")[1]!).map(([k, v]) => ["audit only", k, v]),
  ]);
  for (const k of [...onlyMine.slice(0, 10), ...onlyTheirs.slice(0, 10)]) p(`- ${onlyMine.includes(k) ? "TS" : "audit"} only: ${k}`);
  p();
}
const chosenDis = ob.filter((k) => Boolean(mo.get(k)!["is_chosen"]) !== Boolean(ao.get(k)!["is_chosen"]));
if (chosenDis.length) {
  p("is_chosen disagreements:");
  p();
  for (const k of chosenDis.slice(0, 20)) p(`- ${k}: TS ${mo.get(k)!["is_chosen"]}, audit ${ao.get(k)!["is_chosen"]}`);
  p();
}

// ------------------------------------------------------------------ verification diff rows
p("## 3. Changes to the 922 build 1 species (changelog vs verification_diff_build1)");
p();
const b1ids = new Set(species.filter((r) => Number(r["added_in_build"]) === 1).map((r) => String(r["id"])));
const ckey = (t: unknown, k: unknown, f: unknown) => `${t}|${k}|${f}`;
const isOrig = (rk: string) => b1ids.has(rk.split(":")[0]!);
const mc = new Map<string, Row[]>();
for (const r of changelog) {
  if (!isOrig(String(r["row_key"]))) continue;
  const k = ckey(r["table"], r["row_key"], r["field"]);
  (mc.get(k) ?? mc.set(k, []).get(k)!).push(r);
}
const ac = new Map<string, Row[]>();
for (const r of vdiff) {
  if (r["species_id"] === null) continue;
  const k = ckey(r["table"], r["row_key"], r["field"]);
  (ac.get(k) ?? ac.set(k, []).get(k)!).push(r);
}
const ckBoth = [...mc.keys()].filter((k) => ac.has(k));
const valAgree = ckBoth.filter((k) => {
  const a = ac.get(k)!;
  const m = mc.get(k)!;
  return a.some((x) => m.some((y) => sameValue(x["build1_value"], y["old_value"]) && sameValue(x["current_value"], y["new_value"])));
});
const ctAgree = ckBoth.filter((k) => ac.get(k)!.some((x) => mc.get(k)!.some((y) => x["change_type"] === y["change_type"])));
const dcAgree = ckBoth.filter((k) => ac.get(k)!.some((x) => mc.get(k)!.some((y) => x["diff_class"] === y["diff_class"])));
table(["", "count"], [
  ["changelog field rows on build 1 species (TS, keys)", mc.size],
  ["verification diff field rows (audit, keys)", ac.size],
  ["same (table, row_key, field)", ckBoth.length],
  ["old and new value agree", `${valAgree.length}/${ckBoth.length} (${pct(valAgree.length, ckBoth.length)})`],
  ["change_type agrees", `${ctAgree.length}/${ckBoth.length} (${pct(ctAgree.length, ckBoth.length)})`],
  ["diff_class agrees", `${dcAgree.length}/${ckBoth.length} (${pct(dcAgree.length, ckBoth.length)})`],
  ["only TS", mc.size - ckBoth.length],
  ["only audit", ac.size - ckBoth.length],
]);
const first = (m: Map<string, Row[]>, k: string, f: string) => s(m.get(k)![0]![f]);
p("Keys only in the audit, by audit table and diff_class:");
p();
table(["table", "audit diff_class", "rows"], countBy([...ac.keys()].filter((k) => !mc.has(k)), (k) => `${k.split("|")[0]} | ${first(ac, k, "diff_class")}`).map(([k, v]) => [...k.split(" | "), v]));
p("Keys only in the TS changelog, by table and diff_class:");
p();
table(["table", "TS diff_class", "rows"], countBy([...mc.keys()].filter((k) => !ac.has(k)), (k) => `${k.split("|")[0]} | ${first(mc, k, "diff_class")}`).map(([k, v]) => [...k.split(" | "), v]));
p("Keys in both with a different diff_class (audit -> TS):");
p();
table(["audit diff_class", "TS diff_class", "rows"], countBy(ckBoth.filter((k) => !dcAgree.includes(k)), (k) => `${first(ac, k, "diff_class")} | ${first(mc, k, "diff_class")}`).map(([k, v]) => [...k.split(" | "), v]));
const valDis = ckBoth.filter((k) => !valAgree.includes(k));
if (valDis.length) {
  p("Keys in both with different values (first 25):");
  p();
  for (const k of valDis.slice(0, 25)) p(`- ${k}: audit ${first(ac, k, "build1_value")} -> ${first(ac, k, "current_value")} (${first(ac, k, "diff_class")}); TS ${first(mc, k, "old_value")} -> ${first(mc, k, "new_value")} (${first(mc, k, "diff_class")})`);
  p();
}

// ------------------------------------------------------------------ record status and RefSeq status
p("## 4. Record status of build 1 species");
p();
const byId = new Map(species.map((r) => [String(r["id"]), r]));
const cross = countBy(vsum, (r) => `${r["proposed_record_status"]} | ${byId.get(String(r["species_id"]))?.["record_status"]}`);
table(["audit proposed_record_status", "TS record_status", "species"], cross.map(([k, v]) => [...k.split(" | "), v]));
p("RefSeq status (audit: NCBI esummary of 2026-11-13; TS: presence in RefSeq release 237):");
p();
const rsRows = vsum.map((r) => {
  const m = byId.get(String(r["species_id"]))!;
  const audit = r["refseq_current_status"] === "live" ? (r["refseq_version_changed"] ? "live, new version" : "live") : r["successor_refseq_candidates"] ? "suppressed, successor" : "suppressed, none";
  const ts = m["record_status"] === "retired" && String(m["retired_reason"] ?? "").startsWith("RefSeq") ? "retired (no record)" : m["refseq"] === r["refseq_build1"] ? "same accession.version" : String(m["refseq"]).split(".")[0] === String(r["refseq_build1"]).split(".")[0] ? "new version" : "successor";
  const succOk = ts === "successor" ? String(r["successor_refseq_candidates"] ?? "").includes(String(m["refseq"])) : null;
  return { audit, ts, succOk, name: String(r["scientific_name_build1"]), refseq: String(m["refseq"]) };
});
table(["audit", "TS", "species"], countBy(rsRows, (r) => `${r.audit} | ${r.ts}`).map(([k, v]) => [...k.split(" | "), v]));
const succ = rsRows.filter((r) => r.succOk !== null);
p(`Successor chosen by TS is among the audit's live successor candidates: ${succ.filter((r) => r.succOk).length}/${succ.length}.`);
for (const r of succ.filter((x) => !x.succOk)) p(`- ${r.name}: TS ${r.refseq} not among the audit candidates`);
p();

// ------------------------------------------------------------------ names
p("## 5. Names");
p();
const nm = vsum.map((r) => {
  const m = byId.get(String(r["species_id"]))!;
  const renamed = String(m["previous_scientific_names"] ?? "") !== "";
  return { audit: s(r["ncbi_name_change"]) || "(none)", ts: renamed ? `renamed to NCBI name` : "kept", agree: !renamed || m["scientific_name"] === r["ncbi_species_name"] };
});
table(["audit ncbi_name_change", "TS", "species"], countBy(nm, (r) => `${r.audit} | ${r.ts}`).map(([k, v]) => [...k.split(" | "), v]));
p(`Renamed rows whose new name equals the audit's NCBI species name: ${nm.filter((r) => r.ts !== "kept" && r.agree).length}/${nm.filter((r) => r.ts !== "kept").length}.`);
p();
console.log(out.join("\n"));
